export const sceneAt = (v: number) => {
  let i = 0;
  SCENES.forEach((s, k) => {
    if (v >= s.start) i = k;
  });
  const sc = SCENES[i];
  const end = i < SCENES.length - 1 ? SCENES[i + 1].start : DURATION_SEC - OFF;
  return { sc, idx: i, local: v - sc.start, dur: end - sc.start, end };
};

